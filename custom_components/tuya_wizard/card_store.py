def _store(hass: HomeAssistant) -> Store:
    return Store(hass, CARD_STORE_VERSION, CARD_STORE_KEY)


async def load(hass: HomeAssistant) -> list[CardTemplate]:
    data = await _store(hass).async_load()
    if not data:
        # First run: seed with built-in templates
        data = {"templates": _BUILTIN_TEMPLATES}
        await _store(hass).async_save(data)
        _LOGGER.debug(
            "Card store seeded with %d built-in templates", len(_BUILTIN_TEMPLATES)
        )
    return [CardTemplate(**t) for t in data.get("templates", [])]


async def upsert(hass: HomeAssistant, template: CardTemplate) -> None:
    templates = await load(hass)
    templates = [t for t in templates if t.id != template.id]
    templates.append(template)
    await _store(hass).async_save({"templates": [t.model_dump() for t in templates]})


async def delete(hass: HomeAssistant, template_id: str) -> bool:
    """Delete a template. Returns False if not found or if it is a builtin."""
    templates = await load(hass)
    target = next((t for t in templates if t.id == template_id), None)
    if target is None:
        return False
    if target.source == "builtin":
        return False
    updated = [t for t in templates if t.id != template_id]
    await _store(hass).async_save({"templates": [t.model_dump() for t in updated]})
    return True


def generate_card_js(template: CardTemplate) -> str:
    """Generate a standalone Lovelace JS card from a CardTemplate."""
    card_type = f"tuya-{template.id}-card"
    main_dp_ids = [e.id for e in template.main_dps]
    advanced_dp_ids = [e.id for e in template.advanced_dps]
    main_labels = {e.id: e.label for e in template.main_dps}
    advanced_labels = {e.id: e.label for e in template.advanced_dps}

    return f"""// Auto-generated by Tuya Wizard — do not edit manually.
// Template: {template.name}  id: {template.id}
import {{ html, LitElement }} from "https://unpkg.com/lit@2/index.js?module";

const CARD_TYPE = "{card_type}";
const MAIN_DPS = {main_dp_ids!r};
const ADVANCED_DPS = {advanced_dp_ids!r};
const LABELS = {{...{main_labels!r}, ...{advanced_labels!r}}};

class TuyaCustomCard extends LitElement {{
  static get properties() {{
    return {{ hass: {{}}, config: {{}} }};
  }}

  setConfig(config) {{
    this.config = config;
  }}

  _entityId(dp) {{
    return this.config[`dp_${{dp}}`] || null;
  }}

  _toggle(entityId) {{
    this.hass.callService("switch", "toggle", {{ entity_id: entityId }});
  }}

  _renderDp(dp, advanced = false) {{
    const entityId = this._entityId(dp);
    if (!entityId) return html``;
    const state = this.hass.states[entityId];
    const label = LABELS[dp] || dp;
    const val = state ? state.state : "—";
    return html`
      <div class="dp-row ${{advanced ? "advanced" : ""}}">
        <span class="label">${{label}}</span>
        <span class="value">${{val}}</span>
      </div>`;
  }}

  render() {{
    if (!this.hass || !this.config) return html``;
    return html`
      <ha-card header="${{this.config.title || "{template.name}"}}">
        <div class="card-content main">
          ${{MAIN_DPS.map(dp => this._renderDp(dp))}}
        </div>
        <details>
          <summary>Avançado</summary>
          <div class="card-content advanced">
            ${{ADVANCED_DPS.map(dp => this._renderDp(dp, true))}}
          </div>
        </details>
      </ha-card>`;
  }}

  static get styles() {{
    return html`<style>
      .dp-row {{ display: flex; justify-content: space-between; padding: 4px 0; }}
      .label {{ color: var(--secondary-text-color); }}
      .value {{ font-weight: bold; }}
      details summary {{ cursor: pointer; padding: 8px 0; color: var(--primary-color); }}
    </style>`;
  }}
}}

customElements.define(CARD_TYPE, TuyaCustomCard);
window.customCards = window.customCards || [];
window.customCards.push({{ type: CARD_TYPE, name: "{template.name}", preview: false }});
"""


async def deploy_card(hass: HomeAssistant, template: CardTemplate) -> tuple[bool, str]:
    """Write the generated JS to /config/www/tuya_wizard_cards/ and register it."""
    from .const import CARDS_WWW_DIR

    try:
        cards_dir = Path(CARDS_WWW_DIR)
        await hass.async_add_executor_job(cards_dir.mkdir, 0o755, True, True)

        card_file = cards_dir / f"tuya-{template.id}-card.js"
        js_content = generate_card_js(template)
        await hass.async_add_executor_job(card_file.write_text, js_content, "utf-8")

        # Register Lovelace resource
        url = f"/local/tuya_wizard_cards/tuya-{template.id}-card.js"
        await _register_lovelace_resource(hass, url)

        return True, f"Card '{template.name}' gerado em {card_file}"
    except Exception as exc:
        _LOGGER.error("Card deploy failed for %s: %s", template.id, exc)
        return False, str(exc)


async def _register_lovelace_resource(hass: HomeAssistant, url: str) -> None:
    try:
        lovelace = hass.data.get("lovelace")
        if lovelace is None:
            return
        resources = lovelace.get("resources")
        if resources is None:
            return
        existing = [r for r in await resources.async_load(True) if r.get("url") == url]
        if not existing:
            await resources.async_create_item({"res_type": "module", "url": url})
    except Exception as exc:
        _LOGGER.debug("Lovelace resource registration skipped: %s", exc)
